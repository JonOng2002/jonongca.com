import figlet from 'figlet';
import ansiShadow from 'figlet/importable-fonts/ANSI Shadow.js';
import { writeFile } from 'node:fs/promises';

figlet.parseFont('ANSI Shadow', ansiShadow);
const wordmark = figlet.textSync('JONONGCA', {
  font: 'ANSI Shadow',
  horizontalLayout: 'default',
  verticalLayout: 'default',
});

const output = `// Generated by scripts/generate-wordmark.mjs. Do not edit by hand.\nexport const jonongcaWordmark = ${JSON.stringify(wordmark)};\n`;
await writeFile(new URL('../src/data/jonongca-wordmark.ts', import.meta.url), output);
